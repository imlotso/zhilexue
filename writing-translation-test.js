'use strict';
const assert = require('assert');
const XLSX = require('xlsx');
const { judgeQ } = require('./src/bank-judge');
const { parseWordQuestions } = require('./src/wordq');
const { parseBankWorkbook } = require('./src/bank-excel');
const { presentAttempt } = require('./src/paper-attempt');
const QSubtype = require('./public/js/question-subtypes');
assert.strictEqual(QSubtype.compatible('书面表达', '英语', 'answer'), 'writing');
assert.strictEqual(QSubtype.compatible('翻译', '英语', 'fill'), 'translation');
assert(judgeQ({ type: 'fill', answer: 'Hello|||Hi' }, ' hi '));
assert(!judgeQ({ type: 'fill', answer: 'Hello|||Hi' }, 'Goodbye'));
assert.throws(() => judgeQ({ type: 'answer', question_subtype: 'writing', answer: 'Example' }, 'Example'), /不支持自动判分/);
assert.throws(() => judgeQ({ type: 'fill', question_subtype: 'writing', answer: 'Example' }, 'Example'), /不支持自动判分/);
assert.throws(() => judgeQ({ type: 'fill', question_subtype: 'translation', answer: '' }, 'Example'), /不支持自动判分/);
const word = parseWordQuestions('书面表达题\n1. Write about your school.\n翻译题\n1. 把早上好翻译成英语 ____\n答案：Good morning'.split('\n'));
assert.strictEqual(word.errors.length, 0);
assert.deepStrictEqual(word.list.map((x) => x.question_subtype), ['writing', 'translation']);
assert.strictEqual(word.list[0].answer, '');
const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([['题目','参考范文'],['写一篇短文','']]), '书面表达题');
const excel = parseBankWorkbook(XLSX.write(wb, { type:'buffer', bookType:'xlsx' }));
assert.strictEqual(excel.items[0].question_subtype, 'writing');
assert.strictEqual(excel.items[0].answer, '');
const attempt = presentAttempt({ score: null, detail: JSON.stringify([{ question_id: 1, is_correct: 1, max_score: 40, earned_score: 40 }, { question_id: 2, ungraded: true }]) });
assert.strictEqual(attempt.ungraded_count, 1);
assert.strictEqual(attempt.objective_score, 40);
assert.strictEqual(attempt.objective_score_total, 40);
console.log('翻译参考答案、书面表达导入与客观题分数汇总通过');

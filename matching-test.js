'use strict';
const assert = require('assert');
const match = require('./src/match-question');
const { judgeQ, matchScore } = require('./src/bank-judge');
const subtype = require('./public/js/question-subtypes');
const opts = ['a', 'b', 'c'];
const input = match.normalize(['甲', '乙', '丙'], opts, 'B,A,C');
assert.strictEqual(input.answer, '2,1,3');
assert.strictEqual(subtype.compatible('听力匹配', '英语', 'sort'), 'listen_match');
assert.strictEqual(subtype.compatible('听力匹配', '数学', 'sort'), '');
assert.strictEqual(subtype.compatible('连线题', '数学', 'sort'), 'math_match');
assert.strictEqual(subtype.compatible('连线题', '英语', 'sort'), '');
assert(match.normalize(['甲', '乙'], opts, '1,2').error);
assert(match.normalize(['甲', '乙', '丙'], opts, '1,1,3').error);
assert(match.normalize(['甲', '乙', '丙'], opts, '').error);
assert(judgeQ({ type: 'sort', answer: input.answer }, '2,1,3'));
assert(!judgeQ({ type: 'sort', answer: input.answer }, '1,2,3'));
assert(judgeQ({ type: 'sort', answer: '3,1,2' }, '3,1,2')); // 普通排序题保持现有语义
const left = ['算式一', '算式二', '算式三', '算式四'];
const right = ['[图1]', '[图2]'];
const math = match.normalize(left, right, 'A,B,A,B', false, 'math_match');
assert.strictEqual(math.answer, '1,2,1,2');
assert(match.normalize(left, right, '1,2,1', false, 'math_match').error);
assert(match.normalize(left, right, '1,2,1,3', false, 'math_match').error);
assert(match.normalize(left, right, '1,2,1,2', false, 'listen_match').error);
const q = { type: 'sort', question_subtype: 'math_match', match_prompts: JSON.stringify(left), options: JSON.stringify(right), answer: math.answer };
assert(judgeQ(q, '1,2,1,2'));
assert(judgeQ(q, 'A,B,A,B'));
assert(!judgeQ(q, '1,2,1'));
assert(!judgeQ(q, '1,2,2,1'));
assert.deepStrictEqual(matchScore(q, '1,0,1,0'), { match_correct: 2, match_total: 4, match_parts: [true, false, true, false] });
assert.strictEqual(matchScore(q, '').match_correct, 0);
assert.strictEqual(matchScore(q, '1,2,1,2,1').match_correct, 0);
assert.strictEqual(matchScore({ ...q, question_subtype: 'listen_match', match_prompts: '["甲","乙"]', answer: '2,1' }, '2,0').match_correct, 1);
console.log('数学多对一、听力匹配及普通排序校验和判分通过');
